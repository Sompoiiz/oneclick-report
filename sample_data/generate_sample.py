"""สคริปต์สร้างข้อมูลตัวอย่าง (จำลองผลส่งออกจาก Google Form) ไว้ทดสอบระบบเท่านั้น"""
import numpy as np
import pandas as pd

rng = np.random.default_rng(42)
N = 60

genders = rng.choice(["ชาย", "หญิง"], size=N, p=[0.4, 0.6])
positions = rng.choice(["ครู", "บุคลากรทางการศึกษา", "นักเรียน/นักศึกษา", "อื่นๆ"], size=N)


def likert(n, low_bias=False):
    if low_bias:
        p = [0.03, 0.07, 0.20, 0.40, 0.30]
    else:
        p = [0.02, 0.05, 0.13, 0.45, 0.35]
    return rng.choice([1, 2, 3, 4, 5], size=n, p=p)


feedback_pool = [
    "สถานที่จัดงานค่อนข้างแคบ ควรหาห้องที่ใหญ่กว่านี้",
    "วิทยากรบรรยายดีมาก เข้าใจง่าย อยากให้เชิญมาบรรยายอีก",
    "อยากให้เพิ่มเวลาช่วง workshop ให้มากขึ้น รู้สึกว่าเร่งรีบเกินไป",
    "อาหารกลางวันอร่อยดี แต่คิวยาวไปหน่อย",
    "เอกสารประกอบการอบรมควรแจกล่วงหน้าก่อนวันจริง",
    "ระบบลงทะเบียนหน้างานช้า ควรปรับปรุง",
    "ภาพรวมโครงการดีมาก ประทับใจการจัดงาน",
    "ที่จอดรถไม่เพียงพอ ควรประสานสถานที่จอดรถเพิ่ม",
    "อยากให้จัดกิจกรรมแบบนี้บ่อยขึ้น มีประโยชน์มาก",
    "เนื้อหาบางช่วงยากเกินไปสำหรับผู้เริ่มต้น ควรมีระดับพื้นฐานแยกต่างหาก",
    "วิทยากรตอบคำถามได้ดี แต่เวลาถาม-ตอบน้อยไปหน่อย",
    "ห้องน้ำสะอาดดี การอำนวยความสะดวกโดยรวมดี",
    "สัญญาณ Wifi ในห้องอบรมช้ามาก ควรปรับปรุง",
    "ขอบคุณทีมงานทุกคนที่ตั้งใจจัดงานนี้ครับ",
    "อยากให้มีเอกสารสรุปหลังจบการอบรมส่งให้ทางอีเมล",
    "ระยะเวลาการอบรมยาวไปหน่อย รู้สึกเหนื่อยล้าช่วงบ่าย",
    "กิจกรรมกลุ่มสนุกดี ได้แลกเปลี่ยนความคิดเห็นกับผู้เข้าร่วมคนอื่น",
    "",
    "",
    "ไม่มีข้อเสนอแนะเพิ่มเติม",
]

feedback = rng.choice(feedback_pool, size=N)

df = pd.DataFrame({
    "ประทับเวลา": pd.date_range("2026-08-01", periods=N, freq="h").astype(str),
    "เพศ": genders,
    "ตำแหน่ง": positions,
    "1. การประชาสัมพันธ์โครงการมีความชัดเจน": likert(N),
    "2. ระยะเวลาในการดำเนินโครงการมีความเหมาะสม": likert(N, low_bias=True),
    "3. สถานที่จัดโครงการมีความเหมาะสม": likert(N, low_bias=True),
    "4. ท่านมีความรู้ความเข้าใจเพิ่มขึ้นหลังเข้าร่วมโครงการ": likert(N),
    "5. ท่านสามารถนำความรู้ไปประยุกต์ใช้ได้จริง": likert(N),
    "6. วิทยากรมีความรู้ความสามารถในการถ่ายทอด": likert(N),
    "7. ความพึงพอใจต่อสิ่งอำนวยความสะดวกโดยรวม": likert(N, low_bias=True),
    "ข้อเสนอแนะอื่นๆ": feedback,
})

df.to_csv("sample_data/sample_evaluation.csv", index=False, encoding="utf-8-sig")
print(f"สร้างไฟล์ตัวอย่างสำเร็จ: {len(df)} แถว")
